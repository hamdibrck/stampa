import { createHash } from 'node:crypto';

import { normalizeSearch } from '@stampa/shared';

import { countryAt, type CountryCollection } from './geo';
import type { City, Country, Enrichment, GeoNamesCountry, SelectedCity } from './types';

/** Wikidata labels are sometimes disambiguated ("Springfield, Illinois"); keep the plain name. */
function cleanLabel(label: string | null | undefined): string | null {
  const t = label?.split(/,| \(/)[0]?.trim();
  return t && t.length <= 48 ? t : null;
}

export function mergeCities(selected: SelectedCity[], enrichment: Map<number, Enrichment>): City[] {
  return selected.map((c) => {
    const e = enrichment.get(c.id);
    const labelEn = c.nameLocked ? null : cleanLabel(e?.labelEn);
    const labelTr = c.nameLocked ? null : cleanLabel(e?.labelTr);
    const nameEn = labelEn ?? c.name;
    return {
      ...c,
      nameEn,
      nameTr: c.nameTr ?? labelTr ?? nameEn,
      summaryTr: e?.summaryTr ?? null,
      summaryEn: e?.summaryEn ?? null,
    };
  });
}

export function buildCountries(
  infos: GeoNamesCountry[],
  cities: City[],
  trNames: Map<string, string>,
  geo: CountryCollection,
): Country[] {
  const counts = new Map<string, number>();
  const largest = new Map<string, City>();
  for (const c of cities) {
    counts.set(c.countryCode, (counts.get(c.countryCode) ?? 0) + 1);
    const cur = largest.get(c.countryCode);
    if (!cur || c.population > cur.population) largest.set(c.countryCode, c);
  }
  const hasPolygon = new Set(geo.features.map((f) => f.properties.iso2));
  return infos
    .map((info) => {
      const big = largest.get(info.iso2);
      const geomRef = hasPolygon.has(info.iso2)
        ? info.iso2
        : ((big ? countryAt(geo, big.lon, big.lat) : null) ?? GEOM_FALLBACK[info.iso2] ?? null);
      return {
        iso2: info.iso2,
        iso3: info.iso3,
        nameEn: info.name,
        nameTr: trNames.get(info.iso2) ?? info.name,
        cityCount: counts.get(info.iso2) ?? 0,
        geomRef,
      };
    })
    .sort((a, b) => a.iso2.localeCompare(b.iso2));
}

/** Overseas territories drawn as part of another country, when the point lookup misses. */
const GEOM_FALLBACK: Record<string, string> = {
  GP: 'FR',
  MQ: 'FR',
  GF: 'FR',
  RE: 'FR',
  YT: 'FR',
  BQ: 'NL',
  CC: 'AU',
  CX: 'AU',
};

const round = (n: number, digits: number) => Number(n.toFixed(digits));

/**
 * Column-oriented city bundle embedded in the app. Summaries are not included (lazy-loaded).
 * `dataVersion` is a content hash, so identical input always produces an identical file.
 */
export function buildCityBundle(cities: City[]) {
  const admin1Names = [...new Set(cities.map((c) => c.admin1 ?? ''))].sort();
  const admin1Index = new Map(admin1Names.map((n, i) => [n, i]));
  const body = {
    count: cities.length,
    id: cities.map((c) => c.id),
    nameTr: cities.map((c) => c.nameTr),
    /** Empty string = same as nameTr. */
    nameEn: cities.map((c) => (c.nameEn === c.nameTr ? '' : c.nameEn)),
    country: cities.map((c) => c.countryCode),
    admin1Names,
    admin1: cities.map((c) => admin1Index.get(c.admin1 ?? '') ?? 0),
    lat: cities.map((c) => round(c.lat, 3)),
    lon: cities.map((c) => round(c.lon, 3)),
    population: cities.map((c) => c.population),
    capitals: cities.filter((c) => c.isCapital).map((c) => c.id),
    plates: Object.fromEntries(
      cities.filter((c) => c.plateCode).map((c) => [String(c.id), c.plateCode]),
    ),
  };
  const dataVersion = createHash('sha1').update(JSON.stringify(body)).digest('hex').slice(0, 12);
  return { schema: 1, dataVersion, ...body };
}

export function buildCountryBundle(countries: Country[], cities: City[]) {
  const boxes = new Map<string, [number, number, number, number]>();
  for (const c of cities) {
    const b = boxes.get(c.countryCode);
    if (!b) boxes.set(c.countryCode, [c.lon, c.lat, c.lon, c.lat]);
    else {
      b[0] = Math.min(b[0], c.lon);
      b[1] = Math.min(b[1], c.lat);
      b[2] = Math.max(b[2], c.lon);
      b[3] = Math.max(b[3], c.lat);
    }
  }
  return {
    schema: 1,
    countries: countries
      .filter((c) => c.cityCount > 0)
      .map((c) => ({
        iso2: c.iso2,
        nameTr: c.nameTr,
        nameEn: c.nameEn,
        cityCount: c.cityCount,
        geomRef: c.geomRef,
        /** [west, south, east, north] of the country's cities. */
        bbox: (boxes.get(c.iso2) ?? [0, 0, 0, 0]).map((n) => round(n, 2)),
      })),
  };
}

const q = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);

/** Idempotent seed: upserts keyed by the permanent GeoNames id / ISO code. */
export function buildSeedSql(
  countries: Country[],
  cities: City[],
): { countries: string; cities: string } {
  const header = '-- Generated by scripts/cities (pnpm cities build). Do not edit by hand.\n';
  const countryRows = countries
    .map(
      (c) =>
        `(${q(c.iso2)}, ${q(c.iso3)}, ${q(c.nameTr)}, ${q(c.nameEn)}, ${c.cityCount}, ${q(c.geomRef)})`,
    )
    .join(',\n');
  const countriesSql = `${header}insert into public.countries (iso2, iso3, name_tr, name_en, city_count, geom_ref) values
${countryRows}
on conflict (iso2) do update set
  iso3 = excluded.iso3, name_tr = excluded.name_tr, name_en = excluded.name_en,
  city_count = excluded.city_count, geom_ref = excluded.geom_ref;
`;

  const cityRow = (c: City) =>
    `(${c.id}, ${c.id}, ${q(c.countryCode)}, ${q(c.nameTr)}, ${q(c.nameEn)}, ${q(c.asciiName)}, ${q(
      [
        ...new Set([
          normalizeSearch(c.nameTr),
          normalizeSearch(c.nameEn),
          normalizeSearch(c.asciiName),
        ]),
      ].join('|'),
    )}, ${q(c.admin1)}, ${q(c.plateCode)}, ${c.lat}, ${c.lon}, ${c.population}, ${c.isCapital}, ${q(c.summaryTr)}, ${q(c.summaryEn)})`;
  const batches: string[] = [];
  for (let i = 0; i < cities.length; i += 500) {
    batches.push(`insert into public.cities
  (id, geonames_id, country_iso2, name_tr, name_en, name_ascii, search_key, admin1, plate_code, lat, lon, population, is_capital, summary_tr, summary_en)
values
${cities
  .slice(i, i + 500)
  .map(cityRow)
  .join(',\n')}
on conflict (id) do update set
  country_iso2 = excluded.country_iso2, name_tr = excluded.name_tr, name_en = excluded.name_en,
  name_ascii = excluded.name_ascii, search_key = excluded.search_key, admin1 = excluded.admin1,
  plate_code = excluded.plate_code, lat = excluded.lat, lon = excluded.lon,
  population = excluded.population, is_capital = excluded.is_capital,
  summary_tr = excluded.summary_tr, summary_en = excluded.summary_en;
`);
  }
  // Cities that left the dataset are retired, never deleted: visits may reference them.
  const ids = cities.map((c) => c.id).join(',');
  const citiesSql = `${header}${batches.join('\n')}
update public.cities set is_active = (id in (${ids})) where is_active is distinct from (id in (${ids}));
`;
  return { countries: countriesSql, cities: citiesSql };
}
