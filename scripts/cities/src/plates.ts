/** GeoNames spellings that differ from the official province name. */
const ALIASES: Record<string, string> = {
  icel: 'mersin',
  afyon: 'afyonkarahisar',
  'k maras': 'kahramanmaras',
  urfa: 'sanliurfa',
  antep: 'gaziantep',
  izmit: 'kocaeli',
  adapazari: 'sakarya',
  antakya: 'hatay',
};

const byKey = new Map<string, { name: string; plate: string }>(
  TR_PROVINCES.map((name, i) => [
    normalizeSearch(name),
    { name, plate: String(i + 1).padStart(2, '0') },
  ]),
);

/** Official Turkish province name + plate code for a GeoNames admin1 name. */
export function trProvince(admin1Name: string): { name: string; plate: string } | null {
  const key = normalizeSearch(admin1Name.replace(/\s+(province|ili?)$/i, ''));
  return byKey.get(ALIASES[key] ?? key) ?? null;
}
